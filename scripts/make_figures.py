"""Build the README figures in docs/assets/ from real repo data (stdlib only, SVG output).

- t01-log-timeline.svg   hourly accepted vs signature-mismatch counts from env/logs/mes-webhook.log
- t01-calibration.svg    pass rate per batch from calibration/runs-*/summary.json
- t01-validate.svg       actual output of scripts/validate.py and two negative controls
- t01-agent-run.svg      tool calls and final answer of one recorded agent run

Usage: python3 scripts/make_figures.py
"""
import collections
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
TASK = ROOT / "tasks" / "T01-webhook-401"
OUT = ROOT / "docs" / "assets"
FONT = "font-family='ui-monospace,SFMono-Regular,Menlo,Consolas,monospace'"
SANS = "font-family='-apple-system,Segoe UI,Helvetica,Arial,sans-serif'"
# Plausible wrong fixes; each must FAIL the grader. (label, file in env/, old text, new text)
CONTROLS = [
    ("narrow fix: ensure_ascii=False in middleware", "service/middleware.py",
     "body = json.dumps(data).encode()", "body = json.dumps(data, ensure_ascii=False).encode()"),
    ("global fix: middleware passes raw bytes to all routes", "service/middleware.py",
     "body = json.dumps(data).encode()", "body = raw"),
    ("bypass: MES signature check removed", "service/signing.py",
     'if not hmac.compare_digest(headers.get("X-MES-Signature", ""), "sha256=" + mac.hexdigest()):',
     "if False:"),
]
INK, MUTED, GRID, OK, BAD, BAND = "#1f2328", "#59636e", "#d1d9e0", "#4a72b0", "#cf222e", "#dafbe1"


def save(name, w, h, body):
    OUT.mkdir(parents=True, exist_ok=True)
    svg = ("<svg xmlns='http://www.w3.org/2000/svg' width='%d' height='%d' viewBox='0 0 %d %d'>"
           "<rect width='100%%' height='100%%' fill='#ffffff' rx='8'/>%s</svg>\n") % (w, h, w, h, body)
    (OUT / name).write_text(svg, encoding="utf-8")
    print("wrote", OUT / name)


def text(x, y, s, size=12, fill=INK, anchor="start", weight="normal", font=SANS):
    return "<text x='%s' y='%s' font-size='%s' fill='%s' text-anchor='%s' font-weight='%s' %s>%s</text>" % (
        x, y, size, fill, anchor, weight, font, escape(s))


def log_timeline():
    hours = collections.OrderedDict()
    for line in (TASK / "env" / "logs" / "mes-webhook.log").read_text(encoding="utf-8").splitlines():
        h = line[:13]  # YYYY-MM-DD HH
        c = hours.setdefault(h, [0, 0])
        if "mes_webhook accepted" in line:
            c[0] += 1
        elif "signature mismatch" in line:
            c[1] += 1
    W, H, L, R, T, B = 900, 330, 56, 20, 56, 56
    n, top = len(hours), max(a + b for a, b in hours.values())
    bw = (W - L - R) / n
    sy = (H - T - B) / top
    parts = [text(L, 26, "T01 incident log: webhooks per hour", 15, weight="600"),
             text(L, 44, "Source: env/logs/mes-webhook.log (%d lines, generated by authoring/gen_logs.py)"
                  % sum(1 for _ in (TASK / "env" / "logs" / "mes-webhook.log").open(encoding="utf-8")), 11, MUTED)]
    for v in range(0, top + 1, 50):
        y = H - B - v * sy
        parts.append("<line x1='%d' x2='%d' y1='%.1f' y2='%.1f' stroke='%s'/>" % (L, W - R, y, y, GRID))
        parts.append(text(L - 6, y + 4, str(v), 10, MUTED, "end"))
    for i, (h, (ok, bad)) in enumerate(hours.items()):
        x = L + i * bw
        parts.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='%s'/>" % (
            x + 1, H - B - ok * sy, bw - 2, ok * sy, OK))
        parts.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='%s'/>" % (
            x + 1, H - B - (ok + bad) * sy, bw - 2, bad * sy, BAD))
        if i % 4 == 0:
            parts.append(text(x + bw / 2, H - B + 16, h[5:].replace(" ", " ") + ":00", 10, MUTED, "middle"))
    first_bad = next(i for i, (_, (_, b)) in enumerate(hours.items()) if b)
    xb = L + first_bad * bw
    parts.append("<line x1='%.1f' x2='%.1f' y1='%d' y2='%d' stroke='%s' stroke-dasharray='4 3'/>" % (
        xb, xb, T, H - B, INK))
    parts.append(text(xb + 6, T + 10, "first 401 (bad deploy, not logged)", 11, INK))
    parts.append("<rect x='%d' y='%d' width='10' height='10' fill='%s'/>" % (W - 300, H - 22, OK))
    parts.append(text(W - 285, H - 13, "accepted", 11, MUTED))
    parts.append("<rect x='%d' y='%d' width='10' height='10' fill='%s'/>" % (W - 200, H - 22, BAD))
    parts.append(text(W - 185, H - 13, "signature mismatch (401)", 11, MUTED))
    parts.append(text(L, H - 13, "hour (UTC)", 11, MUTED))
    save("t01-log-timeline.svg", W, H, "".join(parts))


def calibration():
    batches = []
    for f in sorted((TASK / "calibration").glob("runs-*/summary.json")):
        d = json.loads(f.read_text())
        runs = d["runs"]
        batches.append((f.parent.name.replace("runs-", ""), d["pass_automated"], d["total"],
                        min(r["turns"] for r in runs), max(r["turns"] for r in runs),
                        sum(r["cost_usd"] for r in runs)))
    labels = {"2026-11-17": "Batch A: default knobs", "2026-11-17b": "Batch B: no docs, 23k log lines",
              "2026-11-17c": "Batch C: gateway v2, ERP trap"}
    W, L, R, T, rowh = 900, 250, 40, 70, 56
    H = T + rowh * len(batches) + 50
    span = W - L - R
    parts = [text(24, 28, "T01 calibration: Claude Code (claude-opus-5-5), 10 runs per batch", 15, weight="600"),
             text(24, 46, "Green band = target pass rate 20-60 %. Source: tasks/T01-webhook-401/calibration/runs-*/summary.json",
                  11, MUTED),
             "<rect x='%.1f' y='%d' width='%.1f' height='%d' fill='%s'/>" % (
                 L + 0.2 * span, T - 10, 0.4 * span, rowh * len(batches) + 10, BAND)]
    for p in range(0, 101, 20):
        x = L + p / 100 * span
        parts.append("<line x1='%.1f' x2='%.1f' y1='%d' y2='%d' stroke='%s'/>" % (
            x, x, T - 10, T + rowh * len(batches), GRID))
        parts.append(text(x, T + rowh * len(batches) + 16, "%d %%" % p, 10, MUTED, "middle"))
    for i, (name, ok, tot, tmin, tmax, cost) in enumerate(batches):
        y = T + i * rowh
        parts.append(text(24, y + 18, labels.get(name, name), 12, INK, weight="600"))
        parts.append(text(24, y + 34, "%d-%d turns, $%.2f total" % (tmin, tmax, cost), 11, MUTED))
        parts.append("<rect x='%d' y='%d' width='%.1f' height='22' fill='%s' rx='3'/>" % (
            L, y + 8, ok / tot * span, OK))
        parts.append(text(L + ok / tot * span - 8, y + 24, "%d/%d pass" % (ok, tot), 12, "#ffffff", "end", "600"))
    parts.append(text(24, H - 12, "Verdict: too easy at all three settings (30/30). Harder tasks need new bug classes, not more decoys.", 12, BAD, weight="600"))
    save("t01-calibration.svg", W, H, "".join(parts))


def terminal(name, title, lines, width_chars=100):
    lines = [(s if len(s) <= width_chars else s[:width_chars - 1] + "…", c) for s, c in lines]
    W = 28 + width_chars * 7.6  # 12px monospace is ~7.2px/char; leave slack for font fallback
    H = 54 + len(lines) * 17 + 14
    parts = ["<rect width='100%' height='100%' fill='#0d1117' rx='8'/>",
             "<circle cx='20' cy='18' r='5' fill='#ff5f56'/><circle cx='36' cy='18' r='5' fill='#ffbd2e'/>"
             "<circle cx='52' cy='18' r='5' fill='#27c93f'/>",
             text(W / 2, 22, title, 12, "#8b949e", "middle")]
    for i, (s, color) in enumerate(lines):
        parts.append(text(14, 54 + i * 17, s[:width_chars], 12, color, font=FONT))
    save(name, int(W), int(H), "".join(parts))


def color_for(s):
    if "FAIL" in s and "expected" not in s:
        return "#ff7b72"
    if "PASS" in s or " ok" in s or "expected" in s:
        return "#7ee787"
    if s.startswith("$"):
        return "#79c0ff"
    return "#c9d1d9"


def validate_output():
    lines = [("$ python3 scripts/validate.py tasks/T01-webhook-401", "#79c0ff")]
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "validate.py"), str(TASK)],
                       capture_output=True, text=True, cwd=str(ROOT))
    out = r.stdout.splitlines()
    for i, s in enumerate(out):
        if s.startswith(("broken env :", "with fix", "Ran ", "FAILED")):
            lines.append((s, color_for(s)))
        elif s.startswith("test_a"):
            # service log lines interleave with unittest output; status is "ok" or on the next line
            status = "ok" if s.endswith(" ok") else next(
                l.strip() for l in out[i + 1:] if l.strip() in ("ok", "FAIL", "ERROR"))
            s = "%-46s %s" % (re.sub(r" \(.*", "", s), status)
            lines.append((s, "#7ee787" if status == "ok" else "#ff7b72"))
    for label, rel, old, new in CONTROLS:
        with tempfile.TemporaryDirectory() as tmp:
            env = pathlib.Path(tmp) / "env"
            shutil.copytree(TASK / "env", env)
            f = env / rel
            assert old in f.read_text(), "negative control no longer applies: " + label
            f.write_text(f.read_text().replace(old, new))
            r = subprocess.run([sys.executable, str(ROOT / "scripts" / "validate.py"), str(TASK), "--candidate", str(env)],
                               capture_output=True, text=True, cwd=str(ROOT))
        failed = [l.split()[1].replace("test_", "") for l in r.stdout.splitlines() if l.startswith("FAIL:")]
        lines.append(("", INK))
        lines.append(("$ validate.py --candidate <%s>" % label, "#79c0ff"))
        verdict = [l for l in r.stdout.splitlines() if l.startswith("CANDIDATE")][0]
        lines.append(("%s   failed: %s" % (verdict, ", ".join(f.split("_")[0].upper() for f in failed)), "#ff7b72"))
    terminal("t01-validate.svg", "validate.py: broken env, reference fix, negative controls", lines)


def agent_run(run="runs-2026-11-17c/run-03"):
    d = TASK / "calibration" / run
    lines = [("$ claude -p \"$(cat prompt.md)\"   # %s, fresh copy of env/" % run, "#79c0ff")]
    for raw in (d / "transcript.jsonl").read_text().splitlines():
        try:
            ev = json.loads(raw)
        except ValueError:
            continue
        if ev.get("type") != "assistant":
            continue
        for c in ev["message"].get("content", []):
            if c.get("type") == "tool_use":
                i = c["input"]
                arg = i.get("command") or i.get("file_path") or i.get("pattern") or ""
                arg = re.sub(r"/(private/)?var/folders/\S+?/ws-\d+/?", "", arg.splitlines()[0])
                arg = re.sub(r"^cd\s*(&&|;)\s*", "", arg)  # workspace cd is noise once the path is gone
                lines.append(("> %-5s %s" % (c["name"], arg), "#d2a8ff"))
    lines.append(("", INK))
    final = (d / "final.md").read_text()
    words, cur = final.replace("**", "").split(), ""
    wrapped = []
    for w in words:
        if len(cur) + len(w) + 1 > 98:
            wrapped.append(cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    wrapped.append(cur)
    lines += [(s, "#c9d1d9") for s in wrapped[:9]]
    grader = (d / "grader.log").read_text()
    lines.append(("", INK))
    lines.append(("grader: %s" % ("PASS (all grader checks)" if "OK" in grader.splitlines()[-1] else "FAIL"), "#7ee787"))
    terminal("t01-agent-run.svg", "One recorded agent run (tool calls, answer, grade)", lines)


if __name__ == "__main__":
    log_timeline()
    calibration()
    validate_output()
    agent_run()
