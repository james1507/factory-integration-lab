def t02_ingest_rate():
    """Stored readings/s (from the 10 s stats lines) and reconnects per minute, from T02's ingest.log."""
    rate, churn = [], collections.Counter()
    for line in (TASK2 / "env" / "logs" / "ingest.log").read_text().splitlines():
        hhmm = line[11:16]
        m = re.search(r"stored=\d+ \(\+([\d.]+)/s\)", line)
        if m:
            rate.append((line[11:19], float(m.group(1))))
        elif "connection lost" in line:
            churn[hhmm] += 1
    W, H, L, R, T, B = 900, 330, 56, 56, 56, 56
    n = len(rate)
    sx = (W - L - R) / max(1, n - 1)
    top, ctop = 20, max(churn.values()) * 1.1
    y = lambda v: H - B - v / top * (H - T - B)
    parts = [text(L, 26, "T02 ingest log: readings stored per second and reconnects per minute", 15, weight="600"),
             text(L, 44, "Source: env/logs/ingest.log (generated by authoring/gen_logs.py). Sensors send 15 readings/s in total.",
                  11, MUTED)]
    for v in range(0, top + 1, 5):
        parts.append("<line x1='%d' x2='%d' y1='%.1f' y2='%.1f' stroke='%s'/>" % (L, W - R, y(v), y(v), GRID))
        parts.append(text(L - 6, y(v) + 4, str(v), 10, MUTED, "end"))
    minutes = sorted(churn)
    for i, (t, _) in enumerate(rate):
        if t[3:5] in ("00", "30") and t[6:8] == "00":
            parts.append(text(L + i * sx, H - B + 16, t[:5], 10, MUTED, "middle"))
    first = next(i for i, (t, _) in enumerate(rate) if t[:5] >= minutes[0])
    bw = sx * 6
    for mnt, c in churn.items():
        i = next((j for j, (t, _) in enumerate(rate) if t[:5] >= mnt), n - 1)
        h = c / ctop * (H - T - B)
        parts.append("<rect x='%.1f' y='%.1f' width='%.1f' height='%.1f' fill='%s' opacity='0.35'/>" % (
            L + i * sx, H - B - h, bw, h, BAD))
    pts = " ".join("%.1f,%.1f" % (L + i * sx, y(v)) for i, (_, v) in enumerate(rate))
    parts.append("<polyline points='%s' fill='none' stroke='%s' stroke-width='1.5'/>" % (pts, OK))
    x0 = L + first * sx
    parts.append("<line x1='%.1f' x2='%.1f' y1='%d' y2='%d' stroke='%s' stroke-dasharray='4 3'/>" % (x0, x0, T, H - B, INK))
    parts.append(text(x0 + 6, T + 10, "2.4.0 rollout: 3 workers", 11, INK))
    parts.append("<rect x='%d' y='%d' width='14' height='3' fill='%s'/>" % (W - 360, H - 18, OK))
    parts.append(text(W - 340, H - 13, "readings stored/s (left axis)", 11, MUTED))
    parts.append("<rect x='%d' y='%d' width='10' height='10' fill='%s' opacity='0.35'/>" % (W - 160, H - 22, BAD))
    parts.append(text(W - 145, H - 13, "reconnects/min", 11, MUTED))
    parts.append(text(L, H - 13, "time (UTC)", 11, MUTED))
    parts.append(text(W - R + 4, T + 4, "%d/min" % round(ctop), 10, BAD))  # right axis: reconnect bar scale
    parts.append(text(W - R + 4, H - B + 4, "0", 10, BAD))
    save("t02-ingest-rate.svg", W, H, "".join(parts))


def calibration():
    batches = []
    for task in (TASK, TASK2, TASK2B):
        for f in sorted((task / "calibration").glob("runs-*/summary.json")):
            d = json.loads(f.read_text())
            runs = d["runs"]
            name = BATCH_LABELS.get((task.name, f.parent.name.replace("runs-", "")), f.parent.name)
            batches.append((name, d["pass_automated"], d["total"],
                            min(r["turns"] for r in runs), max(r["turns"] for r in runs),
                            sum(r["cost_usd"] for r in runs)))
    W, L, R, T, rowh = 900, 250, 40, 70, 56
    H = T + rowh * len(batches) + 50
    span = W - L - R
    parts = [text(24, 28, "Calibration: Claude Code (claude-opus-5-5), 10 runs per batch", 15, weight="600"),
             text(24, 46, "Green band = target pass rate 20-60 %. Source: tasks/*/calibration/runs-*/summary.json",
                  11, MUTED),
             "<rect x='%.1f' y='%d' width='%.1f' height='%d' fill='%s'/>" % (
                 L + 0.2 * span, T - 10, 0.4 * span, rowh * len(batches) + 10, BAND)]
    for p in range(0, 101, 20):
        x = L + p / 100 * span
        parts.append("<line x1='%.1f' x2='%.1f' y1='%d' y2='%d' stroke='%s'/>" % (
            x, x, T - 10, T + rowh * len(batches), GRID))
        parts.append(text(x, T + rowh * len(batches) + 16, "%d %%" % p, 10, MUTED, "middle"))
    for i, (name, ok, tot, tmin, tmax, cost) in enumerate(batches):
        y = T + i * rowh
        parts.append(text(24, y + 18, name, 12, INK, weight="600"))
        parts.append(text(24, y + 34, "%d-%d turns, $%.2f total" % (tmin, tmax, cost), 11, MUTED))
        parts.append("<rect x='%d' y='%d' width='%.1f' height='22' fill='%s' rx='3'/>" % (
            L, y + 8, ok / tot * span, OK))
        if ok:
            parts.append(text(L + ok / tot * span - 8, y + 24, "%d/%d pass" % (ok, tot), 12, "#ffffff", "end", "600"))
        else:
            parts.append(text(L + 8, y + 24, "0/%d pass" % tot, 12, INK, weight="600"))
    parts.append(text(24, H - 12, VERDICT, 12, BAD, weight="600"))
    save("calibration.svg", W, H, "".join(parts))


def terminal(name, title, lines, width_chars=100):
    lines = [(s if len(s) <= width_chars else s[:width_chars - 1] + "…", c) for s, c in lines]
    W = 28 + width_chars * 7.6  # 12px monospace is ~7.2px/char; leave slack for font fallback
    H = 54 + len(lines) * 17 + 14
    parts = ["<rect width='100%' height='100%' fill='#0d1117' rx='8'/>",
             "<circle cx='20' cy='18' r='5' fill='#ff5f56'/><circle cx='36' cy='18' r='5' fill='#ffbd2e'/>"
             "<circle cx='52' cy='18' r='5' fill='#27c93f'/>",
             text(W / 2, 22, title, 12, "#8b949e", "middle")]
    for i, (s, color) in enumerate(lines):
        parts.append(text(14, 54 + i * 17, s[:width_chars], 12, color, font=FONT))
    save(name, int(W), int(H), "".join(parts))


def color_for(s):
    if "FAIL" in s and "expected" not in s:
        return "#ff7b72"
    if "PASS" in s or " ok" in s or "expected" in s:
        return "#7ee787"
    if s.startswith("$"):
        return "#79c0ff"
    return "#c9d1d9"


def validate_output(task=TASK, name="t01-validate.svg"):
    lines = [("$ python3 scripts/validate.py tasks/%s --controls" % task.name, "#79c0ff")]
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "validate.py"), str(task)],
                       capture_output=True, text=True, cwd=str(ROOT))
    out = r.stdout.splitlines()
    for i, s in enumerate(out):
        if s.startswith(("broken env :", "with fix", "Ran ", "FAILED")):
            lines.append((s, color_for(s)))
        elif s.startswith("test_"):
            # service log lines interleave with unittest output; status is "ok" or on a later line
            tail = s.rsplit(" ", 1)[-1]
            status = tail if tail in ("ok", "FAIL", "ERROR") else next(
                l.strip() for l in out[i + 1:] if l.strip() in ("ok", "FAIL", "ERROR"))
            s = "%-46s %s" % (re.sub(r" \(.*", "", s), status)
            lines.append((s, "#7ee787" if status == "ok" else "#ff7b72"))
    lines.append(("", INK))
    for label, ok, failed in run_controls(task):
        lines.append(("control: %s" % label, "#79c0ff"))
        lines.append(("  %s   failed: %s" % ("PASS (BAD)" if ok else "FAIL (expected)",
                                            ", ".join(f.upper() for f in failed)), "#ff7b72" if not ok else "#ffa657"))
    terminal(name, "validate.py --controls: broken env, reference fix, wrong fixes", lines)


def agent_run(run="runs-2026-11-17c/run-03", task=TASK, name="t01-agent-run.svg"):
    d = task / "calibration" / run
    lines = [("$ claude -p \"$(cat prompt.md)\"   # %s, fresh copy of env/" % run, "#79c0ff")]
    for raw in (d / "transcript.jsonl").read_text().splitlines():
        try:
            ev = json.loads(raw)
        except ValueError:
            continue
        if ev.get("type") != "assistant":
            continue
        for c in ev["message"].get("content", []):
            if c.get("type") == "tool_use":
                i = c["input"]
                arg = i.get("command") or i.get("file_path") or i.get("pattern") or ""
                arg = re.sub(r"/(private/)?var/folders/\S+?/ws-\d+/?", "", arg.splitlines()[0])
                arg = re.sub(r"^cd\s*(&&|;)\s*", "", arg)  # workspace cd is noise once the path is gone
                lines.append(("> %-5s %s" % (c["name"], arg), "#d2a8ff"))
    lines.append(("", INK))
    final = (d / "final.md").read_text()
    words, cur = final.replace("**", "").split(), ""
    wrapped = []
    for w in words:
        if len(cur) + len(w) + 1 > 98:
            wrapped.append(cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    wrapped.append(cur)
    lines += [(s, "#c9d1d9") for s in wrapped[:9]]
    grader = (d / "grader.log").read_text()
    lines.append(("", INK))
    if "OK" in grader.splitlines()[-1]:
        lines.append(("grader: PASS (all grader checks)", "#7ee787"))
    else:
        failed = sorted(set(re.findall(r"^FAIL: test_(\w+?)_", grader, re.M)))
        lines.append(("grader: FAIL (%s)" % ", ".join(x.upper() for x in failed), "#ff7b72"))
    terminal(name, "One recorded agent run (tool calls, answer, grade)", lines)


